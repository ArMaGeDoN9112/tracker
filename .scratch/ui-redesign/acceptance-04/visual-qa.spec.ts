import { test, expect } from '@playwright/test'

test('schedule A visual acceptance with real API', async ({ page }) => {
  await page.goto('/?section=basal')
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  const shot = async (name: string) => page.screenshot({ path: `/qa/${name}.png`, fullPage: true })
  const fits = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.getByText('Расписание ещё не задано.', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 375, height: 812 })
  await shot('empty-375')
  await page.getByLabel('Начало расписания — Москва').fill('2012-08-17T06:00')
  await page.getByLabel('Скорость 1, ед/ч').fill('0,50')
  await page.getByRole('button', { name: 'Добавить интервал', exact: true }).click()
  await page.getByLabel('Начало интервала 2').fill('08:00')
  await page.getByLabel('Скорость 2, ед/ч').fill('0,80')
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Затрагиваемый период' })).toBeVisible()
  await shot('preview-375')
  await page.getByRole('button', { name: 'Сохранить расписание', exact: true }).click()
  await expect(page.getByLabel('История расписаний').locator('article')).toHaveCount(1)
  const summary = page.getByLabel('История расписаний').locator('summary').first()
  await summary.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('История расписаний').getByText(/0,50 ед\/ч/)).toBeVisible()
  for (const width of [375, 390, 768, 1280, 1440]) {
    await page.setViewportSize({ width, height: 960 })
    await fits()
    const smallTargets = await page.locator('.basal-schedules input, .basal-schedules button, .basal-schedules summary').evaluateAll(nodes => nodes.filter(node => {
      const box = node.getBoundingClientRect()
      return box.width > 0 && (box.width < 44 || box.height < 44)
    }).map(node => node.textContent || node.id))
    expect(smallTargets).toEqual([])
    await shot(`schedule-${width}`)
  }
  await summary.focus()
  await shot('focus-1440')
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  await page.getByRole('button', { name: 'Сохранить расписание', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Открыть существующую версию' })).toBeVisible()
  await shot('conflict-1440')
  await page.setViewportSize({ width: 375, height: 812 })
  await fits()
  await shot('conflict-375')
  await page.getByRole('link', { name: 'Открыть существующую версию' }).click()
  await expect(summary).toBeFocused()
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  await fits()
  await shot('text-200-375')
  await page.evaluate(() => { document.documentElement.style.fontSize = '' })
  await page.route('**/api/basal-schedules', route => route.abort())
  await page.getByRole('button', { name: 'Обновить историю', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: /истори/ })).toBeVisible()
  await shot('history-error-375')
  await page.unroute('**/api/basal-schedules')
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/basal-schedules', async route => { await gate; await route.continue() })
  await page.getByRole('button', { name: 'Обновить историю', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: /Загру/ })).toBeVisible()
  await shot('history-loading-375')
  release()
})
