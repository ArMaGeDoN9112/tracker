import { test, expect } from '@playwright/test'

test.use({ timezoneId: 'America/Los_Angeles' })

test('summary load can be retried after a network failure', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.route('**/api/glucose-summary?*', route => route.abort(), { times: 1 })
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  const charts = page.getByRole('region', { name: 'Графики сахара' })
  await expect(charts.getByRole('alert')).toBeVisible()
  if (process.env.DIARY_ACCEPTANCE_DIR) await page.screenshot({ path: `${process.env.DIARY_ACCEPTANCE_DIR}/charts-error-${testInfo.project.name}.png`, fullPage: true })
  await page.getByRole('link', { name: 'Настройки', exact: true }).click()
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  await expect(charts.getByRole('table').getByRole('row')).toHaveCount(8)
  await expect(charts.getByRole('alert')).toHaveCount(0)
})

test('a delayed real summary cannot replace the newer period', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  let release!: () => void
  const delayed = new Promise<void>(resolve => { release = resolve })
  let captured!: () => void
  const ready = new Promise<void>(resolve => { captured = resolve })
  await page.route('**/api/glucose-summary?period=week', async route => {
    const response = await route.fetch()
    captured()
    await delayed
    await route.fulfill({ response })
  }, { times: 1 })
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  const charts = page.getByRole('region', { name: 'Графики сахара' })
  await ready
  await expect(charts.getByRole('status')).toHaveText('Загружаем сводку…')
  if (process.env.DIARY_ACCEPTANCE_DIR) await page.screenshot({ path: `${process.env.DIARY_ACCEPTANCE_DIR}/charts-loading-${testInfo.project.name}.png`, fullPage: true })
  await charts.getByLabel('Период', { exact: true }).selectOption('month')
  await charts.getByLabel('Конец периода — Москва').fill('1901-02-02')
  await charts.getByRole('button', { name: 'Показать период' }).click()
  await expect(charts.getByRole('table').getByRole('row')).toHaveCount(31)
  const oldResponse = page.waitForResponse('**/api/glucose-summary?period=week')
  release()
  await oldResponse
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await expect(charts.getByTestId('period-bounds')).toHaveText('1901-01-04 — 1901-02-02 · Москва · обе даты включены')
  await expect(charts.getByRole('status')).toHaveText('В этом периоде нет измерений сахара.')
  if (process.env.DIARY_ACCEPTANCE_DIR) await page.screenshot({ path: `${process.env.DIARY_ACCEPTANCE_DIR}/charts-empty-${testInfo.project.name}.png`, fullPage: true })
})

test('glucose periods, gaps, keyboard day navigation and updated summaries', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByLabel('Сахар, ммоль/л')).toBeVisible()
  await page.getByLabel('Сахар, ммоль/л').fill('6,5')
  await page.getByLabel('Подколка, ед.').fill('0,7')
  await page.getByLabel('Причина подколки').selectOption('food')
  await page.getByLabel('Комментарий', { exact: true }).fill('Черновик при просмотре графиков')
  const draftTime = await page.getByLabel('Время события — Москва').inputValue()
  const month = testInfo.project.name === 'phone' ? '08' : '07'
  const first = `2010-${month}-01`
  const second = `2010-${month}-02`
  const third = `2010-${month}-03`
  await page.evaluate(async ({ first, third }) => {
    const { csrf_token } = await (await fetch('/api/auth/csrf')).json()
    for (const [day, glucose] of [[first, '4.0'], [first, '8.0'], [third, '12.0']]) {
      const response = await fetch('/api/entries', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf_token },
        body: JSON.stringify({ operation_id: crypto.randomUUID(), occurred_at: `${day}T12:00:00+04:00`, glucose }) })
      if (!response.ok) throw new Error('Could not create measurement')
    }
  }, { first, third })
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  const charts = page.getByRole('region', { name: 'Графики сахара' })
  await expect(charts).toBeVisible()
  await charts.getByLabel('Конец периода — Москва').fill(third)
  await charts.getByRole('button', { name: 'Показать период' }).click()
  await expect(charts.getByRole('table').getByRole('row')).toHaveCount(8)
  await expect(charts.getByTestId('period-average')).toHaveText('Среднее за период: 8,0 ммоль/л · измерений: 3')
  await charts.getByLabel('Период', { exact: true }).selectOption('month')
  await charts.getByRole('button', { name: 'Показать период' }).click()
  await expect(charts.getByRole('table').getByRole('row')).toHaveCount(31)
  await charts.getByLabel('Период', { exact: true }).selectOption('custom')
  await charts.getByLabel('Начало периода — Москва').fill(first)
  await charts.getByRole('button', { name: 'Показать период' }).click()
  await expect(charts.getByRole('table').getByRole('row')).toHaveCount(4)
  await expect(charts.getByTestId('period-bounds')).toHaveText(`${first} — ${third} · Москва · обе даты включены`)
  const rows = charts.getByRole('table').getByRole('row')
  await expect(rows.nth(1)).toContainText('6,0')
  await expect(rows.nth(1)).toContainText('4,0')
  await expect(rows.nth(1)).toContainText('8,0')
  await expect(rows.nth(2)).toContainText('Нет измерений')
  await expect(rows.nth(3).getByRole('cell')).toHaveText(['12,0', '12,0', '12,0', '1'])
  await expect(charts.getByRole('application').getByText('ммоль/л', { exact: true })).toBeVisible()
  await expect(charts.getByRole('application').getByText('Измерения', { exact: true })).toBeVisible()
  // All three glucose series must break across the empty day.
  const paths = charts.locator('.recharts-line-curve')
  await expect(paths).toHaveCount(3)
  for (const path of await paths.all()) expect((await path.getAttribute('d'))?.match(/M/g)).toHaveLength(2)
  // Move the pointer away and reach the first day independently of prior hover.
  await page.mouse.move(0, 0)
  await charts.getByRole('application').focus()
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await expect(charts.locator('.recharts-tooltip-wrapper')).toContainText(`${first} · Москва`)
  await expect(charts.locator('.recharts-tooltip-wrapper')).toContainText('ммоль/л')
  await charts.locator('.recharts-line-dot').last().click()
  await expect(page.getByLabel('День — Москва')).toHaveValue(third)
  await expect(page.getByRole('heading', { name: /^Записи дня/ })).toBeFocused()
  await expect(page.getByLabel('Комментарий', { exact: true })).toHaveValue('Черновик при просмотре графиков')
  await expect(page.getByLabel('Время события — Москва')).toHaveValue(draftTime)
  await expect(page.getByLabel('Сахар, ммоль/л')).toHaveValue('6,5')
  await expect(page.getByLabel('Подколка, ед.')).toHaveValue('0,7')
  await expect(page.getByLabel('Причина подколки')).toHaveValue('food')
  await expect(page.locator('.entries > .entry')).toHaveCount(1)
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  if (process.env.DIARY_ACCEPTANCE_DIR) await charts.screenshot({ path: `${process.env.DIARY_ACCEPTANCE_DIR}/glucose-${testInfo.project.name}.png` })
  await charts.locator('.recharts-bar-rectangle').last().click()
  await expect(page.getByLabel('День — Москва')).toHaveValue(third)
  await expect(page.getByRole('heading', { name: /^Записи дня/ })).toBeFocused()
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  await charts.getByRole('button', { name: `Открыть день ${first}` }).press('Enter')
  await expect(page.getByLabel('День — Москва')).toHaveValue(first)
  await expect(page.getByRole('heading', { name: /^Записи дня/ })).toBeFocused()
  await expect(page.locator('.entries > .entry')).toHaveCount(2)
  await page.locator('.entries > .entry').first().getByRole('button', { name: 'Изменить', exact: true }).click()
  await page.getByLabel('Сахар, ммоль/л').fill('10.0')
  await page.getByLabel('Время события — Москва').fill(`${second}T12:00`)
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  await expect(charts.getByTestId('period-average')).toContainText('10,0 ммоль/л · измерений: 3')
  await expect(rows.nth(1)).toContainText('8,0')
  await expect(rows.nth(2)).toContainText('10,0')
  await page.getByRole('link', { name: 'Дневник', exact: true }).click()
  await page.locator('.entries > .entry').getByRole('button', { name: 'Удалить', exact: true }).click()
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  await expect(charts.getByTestId('period-average')).toContainText('10,0 ммоль/л · измерений: 2')
  await expect(rows.nth(2)).toContainText('Нет измерений')
  await page.getByRole('button', { name: 'Отменить удаление', exact: true }).click()
  await expect(rows.nth(2)).toContainText('10,0')
  await expect(charts.getByTestId('period-average')).toContainText('измерений: 3')
  await page.getByRole('link', { name: 'Дневник', exact: true }).click()
  await page.getByLabel('Время события — Москва').fill(`${second}T13:00`)
  await page.getByLabel('Сахар, ммоль/л').fill('14')
  await page.getByRole('button', { name: 'Сохранить запись', exact: true }).click()
  await expect(page.locator('.entries > .entry')).toHaveCount(2)
  await page.getByRole('link', { name: 'Графики', exact: true }).click()
  await expect(charts.getByTestId('period-average')).toContainText('11,0 ммоль/л · измерений: 4')
  await expect(rows.nth(2).getByRole('cell')).toHaveText(['12,0', '10,0', '14,0', '2'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
