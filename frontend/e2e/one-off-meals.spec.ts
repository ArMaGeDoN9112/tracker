test('repeat draft survives source edit and lost response, explicit retry creates one independent event', async ({ page }) => {
  await start(page)
  const name = `Повтор ${crypto.randomUUID()}`
  await page.getByRole('button', { name: 'Добавить разовую еду', exact: true }).click()
  await page.getByLabel('Название строки 1').fill(name)
  await page.getByLabel('Углеводы строки 1, г за исходную порцию').fill('12')
  await page.getByLabel('Время приёма — Москва').fill('2026-10-19T15:00')
  await page.getByRole('button', { name: 'Сохранить приём пищи', exact: true }).click()
  await openSection(page, 'Аналитика питания')
  const saved = history(page).getByRole('article').filter({ hasText: name })
  await saved.getByRole('button', { name: 'Повторить приём', exact: true }).click()
  await expect(page.getByLabel('Название строки 1')).toHaveValue(name)
  const time = await page.getByLabel('Время приёма — Москва').inputValue()
  const prior = (await (await page.request.get('/api/nutrition-day?day=2026-10-19')).json()).meals.find((row: { lines: { name: string }[] }) => row.lines[0].name === name)
  const csrf = (await (await page.request.get('/api/auth/csrf')).json()).csrf_token
  const edit = await page.request.put(`/api/meals/${prior.id}`, { headers: { Origin: 'https://localhost:5173', 'X-CSRF-Token': csrf }, data: {
    operation_id: crypto.randomUUID(), expected_revision: prior.revision, occurred_at: prior.occurred_at, category: 'dinner',
    lines: prior.lines.map(({ totals, ...line }: { totals: unknown; carbohydrate: string }) => ({ ...line, carbohydrate: '24' })),
  } })
  expect(edit.ok()).toBeTruthy()
  await expect(page.getByLabel('Углеводы строки 1, г за исходную порцию')).toHaveValue('12.00')
  const bodies: string[] = []
  page.on('request', request => { if (request.url().endsWith('/api/meals') && request.method() === 'POST') bodies.push(request.postData()!) })
  await page.route('**/api/meals', async route => { const response = await route.fetch(); expect(response.ok()).toBeTruthy(); await route.abort() }, { times: 1 })
  await page.getByRole('button', { name: 'Сохранить приём пищи', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Повторить сохранение приёма', exact: true })).toBeEnabled()
  await page.getByRole('link', { name: 'Настройки', exact: true }).click()
  await page.goBack()
  await expect(page.getByLabel('Название строки 1', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Повторить сохранение приёма', exact: true }).click()
  await expect(form(page).getByRole('status')).toContainText('Приём пищи сохранён')
  expect(bodies).toHaveLength(2)
  expect(bodies[0]).toBe(bodies[1])
  const current = (await (await page.request.get(`/api/nutrition-day?day=${time.slice(0, 10)}`)).json()).meals.filter((row: { lines: { name: string }[] }) => row.lines[0].name === name)
  expect(current).toHaveLength(1)
  expect(current[0].id).not.toBe(prior.id)
  expect(current[0].lines[0].id).not.toBe(prior.lines[0].id)
  expect(current[0].totals.carbohydrate.value).toBe('12.00')
  await openSection(page, 'Аналитика питания')
  await expect(saved).toContainText('24.00 г')
})

