import { openSection } from './navigation'
import { test, expect } from '@playwright/test'

test.use({ timezoneId: 'America/Los_Angeles' })

test('create immutable schedule, retry a lost response and inspect a historical day', async ({ page }, testInfo) => {
  const day = testInfo.project.name === 'phone' ? '2020-08-17' : '2021-08-17'
  await page.goto('/?section=diary')
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.getByLabel('Время события — Москва').fill(`${day}T07:00`)
  await page.getByLabel('Сахар, ммоль/л').fill('5,5')
  await page.getByRole('button', { name: 'Сохранить запись', exact: true }).click()
  await expect(page.locator('.entries > .entry')).toHaveCount(1)
  await openSection(page, 'База')
  await page.getByLabel('Начало расписания — Москва').fill(`${day}T06:00`)
  await page.getByLabel('Скорость 1, ед/ч').fill('0,50')
  await page.getByRole('button', { name: 'Добавить интервал', exact: true }).click()
  await page.getByLabel('Начало интервала 2').fill('08:00')
  await page.getByLabel('Скорость 2, ед/ч').fill('0,80')
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Затрагиваемый период' })).toContainText('06:00')
  await page.getByRole('link', { name: 'Временная база', exact: true }).click()
  await page.getByRole('link', { name: 'Расписание', exact: true }).click()
  await expect(page.getByLabel('Скорость 1, ед/ч')).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Сохранить расписание', exact: true })).toHaveCount(0)
  await page.getByLabel('Начало расписания — Москва').fill(`${day}T06:00`)
  await page.getByLabel('Скорость 1, ед/ч').fill('0,50')
  await page.getByRole('button', { name: 'Добавить интервал', exact: true }).click()
  await page.getByLabel('Начало интервала 2').fill('08:00')
  await page.getByLabel('Скорость 2, ед/ч').fill('0,80')
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Сохранить расписание', exact: true })).toBeVisible()
  const writes: string[] = []
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/basal-schedules')) writes.push(request.postData()!) })
  await page.route('**/api/basal-schedules', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return }
    await route.fetch()
    await route.abort('failed')
  }, { times: 1 })
  await page.getByRole('button', { name: 'Сохранить расписание', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Повторить сохранение расписания', exact: true })).toBeEnabled()
  await page.getByRole('link', { name: 'Настройки', exact: true }).click()
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Вход в дневник' })).toBeVisible()
  const beforeLogin = writes.length
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await openSection(page, 'База')
  await expect(page.getByLabel('Скорость 1, ед/ч')).toHaveValue('')
  await expect(page.getByLabel('Скорость 2, ед/ч')).toHaveCount(0)
  await expect(page.getByRole('status').filter({ hasText: 'Затрагиваемый период' })).toHaveCount(0)
  expect(writes).toHaveLength(beforeLogin)
  await page.getByRole('button', { name: 'Повторить сохранение расписания', exact: true }).click()
  await expect(page.getByLabel('История расписаний').locator(`summary time[datetime^="${day}"]`)).toHaveCount(1)
  await expect(page.getByRole('status').filter({ hasText: 'Расписание сохранено.' })).toBeVisible()
  expect(writes).toHaveLength(beforeLogin + 1)
  expect(writes.every(body => body === writes[0])).toBe(true)
  await openSection(page, 'Ввод сахара')
  await expect(page.locator('.entries > .entry')).toContainText('0,50 ед/ч · по расписанию')
  await expect(page.getByTestId('day-basal')).toContainText('неизвестна')
  await expect(page.locator('.basal-change')).toContainText(['0,50 ед/ч', '0,80 ед/ч'])
  await page.getByLabel('Время события — Москва').fill(`${day}T08:00`)
  await expect(page.getByTestId('form-basal')).toContainText('0,80 ед/ч')
  await page.reload()
  await page.getByLabel('День — Москва').fill(day)
  await expect(page.locator('.entries > .entry')).toContainText('0,50 ед/ч')
  await openSection(page, 'База')
  await page.getByLabel('Начало расписания — Москва').fill(`${day}T06:00`)
  await page.getByLabel('Скорость 1, ед/ч').fill('1')
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  await page.getByRole('button', { name: 'Сохранить расписание', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Открыть существующую версию' })).toHaveAttribute('href', /^#schedule-/)
  await page.getByRole('link', { name: 'Открыть существующую версию' }).click()
  const existing = page.getByLabel('История расписаний').locator('details[open]')
  await expect(existing.locator('summary')).toBeFocused()
  await existing.getByRole('button', { name: '00:00–08:00 · 0,50 ед/ч', exact: true }).focus()
  await expect(existing.getByRole('tooltip')).toContainText('0,50 ед/ч')
  await existing.locator('summary').focus()
  await existing.locator('summary').press('Enter')
  await expect(existing).toHaveCount(0)
})

test('acknowledged schedule stays saved when refresh fails and invalid intervals retain their draft', async ({ page }, testInfo) => {
  const day = testInfo.project.name === 'phone' ? '2041-08-17' : '2040-08-17'
  await page.goto('/?section=basal')
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByLabel('Начало расписания — Москва')).not.toHaveValue('')
  await page.getByLabel('Начало расписания — Москва').fill(`${day}T06:00`)
  await expect(page.getByLabel('Начало интервала 1')).toHaveValue('00:00')
  await expect(page.getByLabel('Начало интервала 1')).toHaveAttribute('readonly', '')
  await page.getByLabel('Скорость 1, ед/ч').fill('0,001')
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  await page.getByRole('button', { name: 'Сохранить расписание', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'два знака после запятой' })).toBeVisible()
  await expect(page.getByLabel('Скорость 1, ед/ч')).toHaveValue('0,001')
  await page.getByLabel('Скорость 1, ед/ч').fill('0,00')
  await page.getByRole('button', { name: 'Добавить интервал', exact: true }).click()
  await page.getByLabel('Начало интервала 2').fill('00:00')
  await page.getByLabel('Скорость 2, ед/ч').fill('1')
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  await page.getByRole('button', { name: 'Сохранить расписание', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'возрастанию' })).toBeVisible()
  await page.getByRole('button', { name: 'Убрать интервал 2', exact: true }).click()
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  let acknowledged = false
  await page.route('**/api/basal-schedules', async route => {
    if (route.request().method() === 'POST') {
      const response = await route.fetch()
      acknowledged = response.ok()
      await route.fulfill({ response })
    } else if (acknowledged) await route.abort('failed')
    else await route.continue()
  })
  await page.getByRole('button', { name: 'Сохранить расписание', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Расписание сохранено.' })).toBeVisible()
  await expect(page.getByRole('alert').filter({ hasText: 'Расписание сохранено, но' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Повторить сохранение расписания', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Скорость 1, ед/ч')).toBeEnabled()
  await page.unroute('**/api/basal-schedules')
  await page.reload()
  const version = page.getByLabel('История расписаний').locator('article').filter({ has: page.locator(`summary time[datetime^="${day}"]`) })
  await expect(version).toHaveCount(1)
  await version.locator('summary').click()
  await version.getByRole('button', { name: '00:00–24:00 · 0,00 ед/ч', exact: true }).focus()
  await expect(version.getByRole('tooltip')).toContainText('0,00 ед/ч')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
