import { test, expect } from '@playwright/test'

test.use({ timezoneId: 'America/Los_Angeles' })

test('create temporary basal, retry lost response, replace and inspect next day', async ({ page }, testInfo) => {
  const day = testInfo.project.name === 'phone' ? '2036-08-17' : '2035-08-17'
  const tomorrow = day.replace('17', '18')
  await page.goto('/')
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  const section = page.getByRole('region', { name: 'Временная база', exact: true })
  await section.getByLabel('Начало временной базы — Москва').fill(`${day}T23:00`)
  await section.getByLabel('Длительность, мин').fill('240')
  await section.getByLabel('Процент от расписания').fill('120')
  await section.getByRole('button', { name: 'Проверить период временной базы', exact: true }).click()
  await expect(section.getByRole('status')).toContainText('Затрагиваемый период')
  await page.route('**/api/temporary-basals', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return }
    await route.fetch()
    await route.abort('failed')
  }, { times: 1 })
  await section.getByRole('button', { name: 'Сохранить временную базу', exact: true }).click()
  await section.getByRole('button', { name: 'Повторить сохранение временной базы', exact: true }).click()
  await expect(section.getByRole('status').filter({ hasText: 'сохранена' })).toBeVisible()
  await page.getByLabel('Начало расписания — Москва').fill(`${day}T00:00`)
  await page.getByLabel('Скорость 1, ед/ч').fill('0,50')
  await page.getByRole('button', { name: 'Проверить период', exact: true }).click()
  await page.getByRole('button', { name: 'Сохранить расписание', exact: true }).click()
  await page.getByLabel('День — Москва').fill(tomorrow)
  await expect(page.getByTestId('day-basal')).toContainText('0,60 ед/ч')
  await expect(page.getByTestId('day-temporary-basal')).toContainText('120%')
  await section.getByLabel('Начало временной базы — Москва').fill(`${tomorrow}T01:00`)
  await section.getByLabel('Длительность, мин').fill('60')
  await section.getByLabel('Процент от расписания').fill('0')
  await section.getByRole('button', { name: 'Проверить период временной базы', exact: true }).click()
  await expect(section.getByRole('status').filter({ hasText: 'Затрагиваемый период' })).toContainText('03:00')
  await section.getByRole('button', { name: 'Сохранить временную базу', exact: true }).click()
  await expect(page.locator('.basal-change')).toContainText(['0,00 ед/ч', '0,50 ед/ч'])
  await expect(page.getByLabel('Временная база дня').locator('article')).toHaveCount(2)
  await expect(page.getByLabel('Временная база дня').locator('article').first()).toContainText('Заданное окончание:')
  await expect(page.getByLabel('Временная база дня').locator('article').first()).toContainText('Эффективное окончание:')
  await page.getByLabel('Время события — Москва').fill(`${tomorrow}T02:00`)
  await expect(page.getByTestId('form-basal')).toContainText('0,50 ед/ч')
  await page.reload()
  await page.getByLabel('День — Москва').fill(tomorrow)
  await expect(page.getByTestId('day-temporary-basal')).toContainText('120%')
  await expect(page.locator('.basal-change')).toHaveCount(2)
})
