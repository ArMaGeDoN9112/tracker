import { test, expect } from '@playwright/test'
import { openSection } from './navigation'

test('input has no history; analysis owns day records and discards closed edits', async ({ page }, info) => {
  const day = info.project.name === 'phone' ? '2091-03-02' : '2090-03-02'
  await page.goto(`/?section=diary&day=${day}`)
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByLabel('Сахар, ммоль/л')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Хронология дня' })).toBeHidden()
  await page.getByLabel('Время события — Москва').fill(`${day}T12:34`)
  await page.getByLabel('Комментарий', { exact: true }).fill('Запись для анализа')
  await page.getByRole('button', { name: 'Сохранить запись', exact: true }).click()
  await expect(page.getByText('Запись сохранена.', { exact: true })).toBeVisible()
  await expect(page).toHaveURL(/section=diary/)
  if (process.env.DIARY_ACCEPTANCE_DIR) await page.screenshot({ path: `${process.env.DIARY_ACCEPTANCE_DIR}/03-input-${info.project.name}.png`, fullPage: true })
  await expect(page.getByRole('region', { name: 'Хронология дня' })).toBeHidden()
  await openSection(page, 'Аналитика сахара')
  await expect(page.getByLabel('День — Москва')).toHaveValue(day)
  const timeline = page.getByRole('region', { name: 'Хронология дня' })
  const bolus = timeline.getByRole('slider', { name: 'Сахар и инсулин по времени' })
  await expect(bolus).toBeVisible()
  await bolus.focus()
  await bolus.press('ArrowRight')
  await expect(timeline.getByRole('tooltip', { name: 'Сахар', exact: true })).toContainText('12:34')
  await expect(timeline.getByRole('tooltip', { name: 'Подколки', exact: true })).toContainText('12:34')
  await timeline.getByText('График базы за день', { exact: true }).click()
  await expect(timeline.locator('.basal-day-chart')).toBeVisible()
  await expect(page.locator('.entries')).toContainText('Запись для анализа')
  await expect(page.getByLabel('Сахар, ммоль/л')).toBeHidden()
  if (process.env.DIARY_ACCEPTANCE_DIR) await page.screenshot({ path: `${process.env.DIARY_ACCEPTANCE_DIR}/03-analysis-${info.project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Изменить', exact: true }).click()
  await page.getByLabel('Комментарий', { exact: true }).fill('Несохранённое исправление')
  if (process.env.DIARY_ACCEPTANCE_DIR) await page.screenshot({ path: `${process.env.DIARY_ACCEPTANCE_DIR}/03-edit-${info.project.name}.png`, fullPage: true })
  await page.getByRole('link', { name: 'Настройки', exact: true }).click()
  await page.goBack()
  await expect(page.getByLabel('Комментарий', { exact: true })).toBeHidden()
  await page.getByRole('button', { name: 'Изменить', exact: true }).click()
  await expect(page.getByLabel('Комментарий', { exact: true })).toHaveValue('Запись для анализа')
  await page.getByLabel('Комментарий', { exact: true }).fill('Правка перед сменой дня')
  await page.getByRole('button', { name: 'Следующий день', exact: true }).click()
  await expect(page.getByLabel('Комментарий', { exact: true })).toBeHidden()
  await page.goBack()
  await page.getByRole('button', { name: 'Изменить', exact: true }).click()
  await expect(page.getByLabel('Комментарий', { exact: true })).toHaveValue('Запись для анализа')
  await page.getByRole('button', { name: 'Отменить редактирование', exact: true }).click()
  await expect(page.getByLabel('Комментарий', { exact: true })).toBeHidden()
  await page.getByRole('link', { name: 'Календарь', exact: true }).click()
  const link = page.getByRole('link', { name: 'Записи диабета', exact: true })
  await expect(link).toHaveAttribute('href', `?section=charts&day=${day}`)
  await link.click()
  await expect(page).toHaveURL(new RegExp(`section=charts&day=${day}`))
  await expect(page.locator('.entries')).toContainText('Запись для анализа')
  await bolus.focus()
  await bolus.press('End')
  await page.getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(timeline).toContainText('Нет записей сахара и подколок.')
  await expect(timeline.getByRole('tooltip')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Отменить удаление', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Календарь', exact: true }).click()
  await page.getByRole('link', { name: 'Записи диабета', exact: true }).click()
  await page.getByRole('button', { name: 'Отменить удаление', exact: true }).click()
  await expect(page.locator('.entries')).toContainText('Запись для анализа')
})

test('late revision conflict cannot reopen an editor on another day', async ({ page }, info) => {
  const day = info.project.name === 'phone' ? '2093-03-02' : '2092-03-02'
  await page.goto(`/?section=charts&day=${day}`)
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Аналитика сахара')
  const headers = { Origin: 'https://localhost:5173', 'X-CSRF-Token': (await (await page.request.get('/api/auth/csrf')).json()).csrf_token }
  const data = { operation_id: crypto.randomUUID(), occurred_at: `${day}T12:00:00+03:00`, comment: 'Исходная запись' }
  const created = await page.request.post('/api/entries', { headers, data })
  expect(created.ok(), await created.text()).toBe(true)
  const receipt = await created.json()
  await page.reload()
  await page.getByRole('button', { name: 'Изменить', exact: true }).click()
  const response = await page.request.put(`/api/entries/${receipt.result_id}`, { headers, data: { ...data, operation_id: crypto.randomUUID(), expected_revision: 1, comment: 'Новая редакция' } })
  expect(response.ok()).toBe(true)
  let release!: () => void
  let reached!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const captured = new Promise<void>(resolve => { reached = resolve })
  await page.route(`**/api/entries/${receipt.result_id}`, async route => {
    const result = await route.fetch()
    expect(result.status()).toBe(409)
    reached()
    await gate
    await route.fulfill({ response: result })
  }, { times: 1 })
  await page.getByLabel('Комментарий', { exact: true }).fill('Несохранённая правка')
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await captured
  await page.getByRole('button', { name: 'Следующий день', exact: true }).click()
  const delivered = page.waitForResponse(`**/api/entries/${receipt.result_id}`)
  release()
  await delivered
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await expect(page.getByRole('button', { name: 'Сохраняем…', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Загрузить актуальную запись', exact: true })).toBeHidden()
  await expect(page.getByLabel('Комментарий', { exact: true })).toBeHidden()
})

test('analysis can recover when opening the default day fails', async ({ page }) => {
  await page.route('**/api/entry-form', route => route.abort(), { times: 1 })
  await page.goto('/?section=charts')
  await page.getByLabel('Логин', { exact: true }).fill('synthetic-owner')
  await page.getByLabel('Пароль', { exact: true }).fill('😀'.repeat(600))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Не удалось открыть форму' })).toBeVisible()
  await page.getByRole('button', { name: 'Повторить подключение', exact: true }).click()
  const server = await (await page.request.get('/api/entry-form')).json()
  await expect(page.getByLabel('День — Москва')).toHaveValue(server.local_time.slice(0, 10))
  await expect(page.getByRole('region', { name: 'Хронология дня' })).toBeVisible()
})
