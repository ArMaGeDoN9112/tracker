import { test, expect } from '@playwright/test'

test('owner logs in, stays signed in after reload, and logs out', async ({ page, context }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Вход в дневник' })).toBeVisible()
  await page.getByLabel('Логин').fill('synthetic-owner')
  const password = '😀'.repeat(600)
  await page.getByLabel('Пароль').fill(password)
  expect((await page.getByLabel('Пароль').inputValue()).length).toBe(1200)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByText('Вы вошли как')).toBeVisible()
  const cookies = await context.cookies()
  const session = cookies.find(cookie => cookie.name === '__Host-diary-session')!
  expect(session.secure && session.httpOnly).toBe(true)
  expect(session.sameSite).toBe('Lax')
  expect(await page.evaluate(() => localStorage.length)).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.reload()
  await expect(page.getByText('Вы вошли как')).toBeVisible()
  const logout = page.getByRole('button', { name: 'Выйти', exact: true })
  const box = await logout.boundingBox()
  expect(box!.height).toBeGreaterThanOrEqual(44)
  expect(box!.width).toBeGreaterThanOrEqual(44)
  await logout.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Вход в дневник' })).toBeVisible()
  expect((await context.cookies()).some(cookie => cookie.name === '__Host-diary-session')).toBe(false)
  await page.reload()
  await expect(page.getByLabel('Пароль')).toBeVisible()
})
